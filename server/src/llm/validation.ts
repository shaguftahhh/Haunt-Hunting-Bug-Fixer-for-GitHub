/**
 * Validation for everything a model returns.
 *
 * Rule: a model is an untrusted data source. We never pass its output straight
 * into the UI or a patch. If a field is missing, out of range, or pointing at a
 * line that does not exist, we drop the finding.
 */
import type { Severity } from '../types.js';

export interface ValidatedFinding {
  line: number;
  endLine: number;
  severity: Severity;
  confidence: number;
  title: string;
  explanation: string;
  whyItMatters: string;
  category: string;
}

const SEVERITIES: Severity[] = ['low', 'medium', 'high'];
const MAX_FINDINGS_PER_FILE = 5;

function clean(value: unknown, max: number): string | null {
  if (typeof value !== 'string') return null;
  const text = value
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (!text) return null;
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
}

export function validateFindings(
  raw: unknown,
  totalLines: number,
): { findings: ValidatedFinding[]; rejected: number } {
  const rejected: string[] = [];
  let list: unknown[] = [];

  if (Array.isArray(raw)) list = raw;
  else if (raw && typeof raw === 'object' && Array.isArray((raw as { findings?: unknown }).findings)) {
    list = (raw as { findings: unknown[] }).findings;
  } else {
    return { findings: [], rejected: 1 };
  }

  const findings: ValidatedFinding[] = [];
  const seen = new Set<string>();

  for (const item of list.slice(0, 12)) {
    if (!item || typeof item !== 'object') {
      rejected.push('not an object');
      continue;
    }
    const obj = item as Record<string, unknown>;
    const line = Number(obj.line);
    if (!Number.isInteger(line) || line < 1 || line > totalLines) {
      rejected.push(`line ${String(obj.line)} out of range`);
      continue;
    }

    const severity = SEVERITIES.includes(obj.severity as Severity) ? (obj.severity as Severity) : null;
    if (!severity) {
      rejected.push('invalid severity');
      continue;
    }

    const title = clean(obj.title, 90);
    const explanation = clean(obj.explanation, 600);
    const whyItMatters = clean(obj.whyItMatters, 600);
    if (!title || !explanation || !whyItMatters) {
      rejected.push('missing explanation fields');
      continue;
    }

    const rawConfidence = Number(obj.confidence);
    const confidence = Number.isFinite(rawConfidence)
      ? Math.min(95, Math.max(20, Math.round(rawConfidence)))
      : 50;

    const rawEnd = Number(obj.endLine);
    const endLine = Number.isInteger(rawEnd) && rawEnd >= line && rawEnd <= totalLines ? rawEnd : line;

    const key = `${line}:${title.toLowerCase()}`;
    if (seen.has(key)) continue;
    seen.add(key);

    findings.push({
      line,
      endLine,
      severity,
      confidence,
      title,
      explanation,
      whyItMatters,
      category: clean(obj.category, 40) ?? 'other',
    });

    if (findings.length >= MAX_FINDINGS_PER_FILE) break;
  }

  return { findings, rejected: rejected.length };
}

export interface ValidatedPatch {
  summary: string;
  testPlan: string;
  prTitle: string;
  diff: string;
}

/**
 * Accept either a JSON object (our prompt) or a bare diff (some hosted models
 * ignore instructions). The diff is always re-validated by patch validation.
 */
export function validatePatchResponse(rawText: string, parsed: unknown): ValidatedPatch {
  if (parsed && typeof parsed === 'object') {
    const obj = parsed as Record<string, unknown>;
    const summary = clean(obj.summary, 500);
    const testPlan = clean(obj.testPlan, 1200);
    const prTitle = clean(obj.prTitle, 80);
    const diff = typeof obj.diff === 'string' ? obj.diff.trim() : '';
    if (diff && summary) {
      return {
        summary: summary,
        testPlan: testPlan ?? 'Run the project’s tests and exercise the affected path manually.',
        prTitle: prTitle ?? 'fix: resolve reported bug',
        diff,
      };
    }
  }

  // Fallback: the reply itself looks like a unified diff.
  const text = rawText.trim();
  if (text.includes('--- ') && text.includes('+++ ') && text.includes('@@')) {
    const fenced = text.replace(/^```(?:diff)?\s*/i, '').replace(/```$/, '').trim();
    return {
      summary: 'Minimal fix generated by the configured model.',
      testPlan: 'Apply the patch, run the test suite, and exercise the affected code path.',
      prTitle: 'fix: resolve reported bug',
      diff: fenced,
    };
  }

  return { summary: '', testPlan: '', prTitle: '', diff: '' };
}
